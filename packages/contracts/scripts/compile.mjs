// Compiles the contracts with solc-js (no native toolchain needed) and writes
// src/artifacts.ts: ABIs, bytecode, and the splitter's CREATE2 address.
//
// evmVersion is pinned to "paris" (no PUSH0) so the same bytecode, and so the
// same CREATE2 address, works on every chain in the registry.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { getContractAddress, keccak256 } from 'viem';

const require = createRequire(import.meta.url);
const solc = require('solc');
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

// Arachnid's deterministic deployment proxy: same address on all EVM chains.
const CREATE2_DEPLOYER = '0x4e59b44847b379578588920cA78FbF26c0B4956C';
const SALT = '0x' + Buffer.from('ShibPayments v1').toString('hex').padEnd(64, '0');

const sources = {};
for (const f of fs.readdirSync(path.join(root, 'contracts'))) {
  sources[f] = { content: fs.readFileSync(path.join(root, 'contracts', f), 'utf8') };
}
const input = {
  language: 'Solidity',
  sources,
  settings: {
    evmVersion: 'paris',
    optimizer: { enabled: true, runs: 10_000 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

const pick = (file, name) => {
  const c = out.contracts[file][name];
  return { abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` };
};
const splitter = pick('ShibPaySplitter.sol', 'ShibPaySplitter');
const testToken = pick('TestToken.sol', 'TestToken');
const splitterAddress = getContractAddress({
  opcode: 'CREATE2',
  from: CREATE2_DEPLOYER,
  salt: SALT,
  bytecodeHash: keccak256(splitter.bytecode),
});

const ts = `// Generated by scripts/compile.mjs with solc ${solc.version()}. Do not edit.

export const CREATE2_DEPLOYER = '${CREATE2_DEPLOYER}' as const;
export const SPLITTER_SALT = '${SALT}' as const;
/** The splitter's address on every chain it is deployed to (CREATE2). */
export const SPLITTER_ADDRESS = '${splitterAddress}' as const;

export const splitterAbi = ${JSON.stringify(splitter.abi, null, 2)} as const;
export const splitterBytecode = '${splitter.bytecode}' as const;

/** Test-only ERC-20. Never deployed to a real chain. */
export const testTokenAbi = ${JSON.stringify(testToken.abi)} as const;
export const testTokenBytecode = '${testToken.bytecode}' as const;
`;
fs.writeFileSync(path.join(root, 'src', 'artifacts.ts'), ts);
fs.writeFileSync(
  path.join(root, 'artifacts.json'),
  JSON.stringify({ CREATE2_DEPLOYER, SALT, splitterAddress, splitter }, null, 2) + '\n',
);
console.log(`Compiled with solc ${solc.version()}; splitter CREATE2 address ${splitterAddress}`);
